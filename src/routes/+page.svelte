<script lang="ts">
	import { goto } from '$app/navigation';
	import { page } from '$app/state';
	import DepartmentBars, { type DepartmentRow } from '#lib/components/DepartmentBars.svelte';
	import EventTable from '#lib/components/EventTable.svelte';
	import FilterBar from '#lib/components/FilterBar.svelte';
	import TrendChart, { type TrendPoint } from '#lib/components/TrendChart.svelte';
	import { query } from '#lib/db.ts';
	import { parseFilters, toSearch, type Filters } from '#lib/filters.ts';
	import { count, duration, percent } from '#lib/format.ts';
	import { departmentSql, summarySql, trendSql } from '#lib/queries.ts';

	type Summary = {
		delivered: number;
		click_rate: number;
		report_rate: number;
		median_seconds: number | null;
		training_rate: number;
	};

	type Dashboard = { summary: Summary; trend: TrendPoint[]; departments: DepartmentRow[] };

	const filters = $derived(parseFilters(page.url.searchParams));
	const search = $derived(toSearch(filters));

	let dashboard = $state<Dashboard | null>(null);
	let error = $state<string | null>(null);
	let loading = $state(true);
	let refreshMs = $state<number | null>(null);
	let requestId = 0;

	async function load(current: Filters, id: number) {
		const started = performance.now();
		try {
			const [summary, trend, departments] = await Promise.all([
				query<Summary>(summarySql(current)),
				query<TrendPoint>(trendSql(current)),
				query<DepartmentRow>(departmentSql(current))
			]);
			if (id !== requestId) return;
			dashboard = {
				summary: summary.rows[0],
				trend: trend.rows,
				departments: departments.rows
			};
			refreshMs = performance.now() - started;
			error = null;
		} catch (cause) {
			if (id === requestId) error = cause instanceof Error ? cause.message : String(cause);
		} finally {
			if (id === requestId) loading = false;
		}
	}

	$effect(() => {
		const current = filters;
		loading = true;
		load(current, ++requestId);
	});

	function update(patch: Partial<Filters>) {
		goto(`${page.url.pathname}${toSearch({ ...filters, ...patch })}`, { reset: false });
	}
</script>

<main>
	<header>
		<div>
			<h1>Drill Insights</h1>
			<p>How employees responded to 48 simulated phishing campaigns.</p>
		</div>
		<p class="badge">Synthetic data</p>
	</header>

	<FilterBar {filters} onchange={update} />

	<p class="status" role="status">
		{#if error}
			Couldn't load the data: {error}
		{:else if loading && !dashboard}
			Loading 1.2 million results in your browser…
		{:else if loading}
			Updating…
		{:else if refreshMs !== null}
			<span data-testid="refresh">Queried in {Math.round(refreshMs)} ms, in your browser.</span>
		{/if}
	</p>

	{#if dashboard}
		<dl class="tiles" data-testid="tiles">
			<div class="panel"><dt>Emails delivered</dt><dd>{count(dashboard.summary.delivered)}</dd></div>
			<div class="panel"><dt>Click rate</dt><dd data-testid="click-rate">{percent(dashboard.summary.click_rate)}</dd></div>
			<div class="panel"><dt>Report rate</dt><dd>{percent(dashboard.summary.report_rate)}</dd></div>
			<div class="panel"><dt>Median time to report</dt><dd>{duration(dashboard.summary.median_seconds)}</dd></div>
			<div class="panel"><dt>Training completed after a click</dt><dd>{percent(dashboard.summary.training_rate)}</dd></div>
		</dl>

		<div class="charts">
			<TrendChart points={dashboard.trend} />
			<DepartmentBars
				rows={dashboard.departments}
				selected={filters.department}
				onselect={(department) => update({ department })}
			/>
		</div>

		{#key search}
			<EventTable {filters} total={dashboard.summary.delivered} />
		{/key}
	{/if}

	<footer>
		All data is generated by a seeded script. It doesn't describe any real company or product.
	</footer>
</main>

